### Python basics
print(1+1)
print(3 - 2)
print(3 / 2)
print(3 * 2)

# This is used to find the remainder 
# THis basically means you can put 2 into 3 ones 
# and have 1 as the remainder. 
print(3 % 2)
print(3 % 1)

# This is used to remove the remainder
# // is only for whole numbers not 0.5 
print(3 // 2)
print(3 // 1)

### Python data types
# integer: can be negative, zero or positive 
(-1, 0, 1)
# float: can be decimal 
(-1.1, 0.0, 1.1)
# complex: can for example be 
(4j + 1)

# String: A collection of one or more characters under single or double quote.
# If a string is more then one sentence then we use tripple quote.
# Example
'Julius'
'Sweden'
'Python is great to know'

# Boolean: A boolean data type either has a True or False value.
# (T and F should always be uppercase values)
True
False

# List: python list is an orderd collection which allows to store different data type items.
# Example 
[0, 1, 2, 3, 4]
['Banana', 10, False, 9.81]

# Dictionary: A python dictionary object is an unorderd collection of data in a key value pair format.
# Example 
{
    'first_name': 'Julius',
    'last_name': 'Skoglund',
    'country': 'Sweden',
    'age': '24'
}

# Tuple: Is an orderd collection of diffrent data types like list but tuples can not 
# be moddified once they are created. They are immutable.
# Example 
('Julius', 'Earth', 'Sweden', 'Stockholm')

# Set: Is a collection of data type similar to list and tuple. Unlike list and tuple set
# is not an orderd collection of items. Like mathematics, set in python stores only uniqu items.
